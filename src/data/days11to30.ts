import type { LessonContent, VocabularyItem, ChunkItem, QuizQuestion } from '../types/learning';

type WordSeed = [string, string, string?];
type ChunkSeed = [string, string, string?];

function buildLesson(
  day: number,
  title: string,
  subtitle: string,
  goal: string,
  words: WordSeed[],
  chunks: ChunkSeed[],
  grammar: LessonContent['grammar'],
  speaking: LessonContent['speaking'],
): LessonContent {
  const vocabulary: VocabularyItem[] = words.map(([portuguese, dutch, weaknessCategory], index) => ({
    id: `w${index + 1}`,
    portuguese,
    dutch,
    weaknessCategory,
  }));
  const builtChunks: ChunkItem[] = chunks.map(([portuguese, dutch, weaknessCategory], index) => ({
    id: `c${index + 1}`,
    portuguese,
    dutch,
    weaknessCategory,
  }));

  const quiz: QuizQuestion[] = [
    ...vocabulary.slice(0, 5).map((item, index) => ({
      id: `q${index + 1}`,
      type: 'input' as const,
      prompt: `Vertaal naar het Portugees: “${item.dutch}”`,
      answer: item.portuguese,
      itemRef: { type: 'word' as const, id: item.id },
    })),
    ...builtChunks.slice(0, 5).map((item, index) => ({
      id: `q${index + 6}`,
      type: 'input' as const,
      prompt: `Vertaal: “${item.dutch}”`,
      answer: item.portuguese,
      itemRef: { type: 'chunk' as const, id: item.id },
    })),
  ];

  return { day, title, subtitle, goal, vocabulary, chunks: builtChunks, grammar, speaking, quiz };
}

